using System;
using System.IO;
using System.Linq;
using System.Threading.Tasks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;
using Xunit;

namespace CodingRules;

public sealed class NamedArgumentReturnConstructionTests
{
    [Theory]
    [InlineData("error", false, 3)]
    [InlineData("none", false, 0)]
    [InlineData("warning", true, 0)]
    public async Task SharedReturnFixtureHonorsSeverityAndGeneratedCode(string severity, bool generated, int expected)
    {
        var source = Read("NamedArguments", "Consumer.cs");
        if (generated) source = "// <auto-generated/>\n#nullable enable\n" + source;
        var config = Read("NamedArguments", ".editorconfig").Replace("CR0500.severity = warning", "CR0500.severity = " + severity);
        var document = NamedArgumentTestFixture.Document(source, config);
        document = document.Project.WithAssemblyName("Consumer").GetDocument(document.Id)!;
        await StatementOperationTestFixture.Compiles(document);
        var diagnostics = await NamedArgumentTestFixture.Diagnostics(document);
        Assert.Equal(expected, diagnostics.Length);
        Assert.All(diagnostics, diagnostic => Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity));
    }

    [Fact]
    public async Task PinnedA9AndOrdinaryReturnShareThePackagedRegression()
    {
        var source = Read("NamedArguments", "Consumer.cs");
        var document = NamedArgumentTestFixture.Document(source, Read("NamedArguments", ".editorconfig"));
        document = document.Project.WithAssemblyName("Consumer").GetDocument(document.Id)!;
        await StatementOperationTestFixture.Compiles(document);
        var diagnostics = await NamedArgumentTestFixture.Diagnostics(document);
        Assert.Equal(3, diagnostics.Length); // Copy, target-typed return, ordinary return; all other cases are accepted.
        Assert.All(diagnostics, diagnostic => Assert.Equal(DiagnosticSeverity.Warning, diagnostic.Severity));
        var originalBindings = await ReturnBindings(document);
        Assert.Equal(2, originalBindings.Length);
        while ((await NamedArgumentTestFixture.Diagnostics(document)).Length != 0)
            document = await NamedArgumentTestFixture.Fix(document);
        document = await StatementOperationTestFixture.Reparse(document);
        Assert.Equal(Read("Expected", "NamedArguments.Fixed.cs.txt"), (await document.GetTextAsync()).ToString());
        Assert.Equal(originalBindings, await ReturnBindings(document));
        Assert.Empty(await NamedArgumentTestFixture.Diagnostics(document));
    }

    [Theory]
    [InlineData("new")]
    [InlineData("new SettingsEdit")]
    public async Task NamingKeepsEffectfulExpressionsAndSelectedOverload(string creation)
    {
        var document = NamedArgumentTestFixture.Document("""
            public sealed class SettingsEdit
            {
                public string Value;
                public SettingsEdit(string File, string Scope, string? Profile, string Key, bool Changed)
                { Value = $"{File}|{Scope}|{Profile}|{Key}|{Changed}"; }
                public SettingsEdit(object File, object Scope, object? Profile, object Key, bool Changed)
                { Value = "wrong overload"; }
            }
            public static class C
            {
                static string trace = "";
                static string Next(string value) { trace += value + ";"; return value; }
                static bool Changed() { trace += "changed;"; return true; }
                static SettingsEdit Create()
                {
                    return CREATION(Next("file"), Next("scope"), Next("profile"), Next("key"), Changed());
                }
                public static string Run()
                {
                    trace = "";
                    var result = Create();
                    return trace + result.Value;
                }
            }
            """.Replace("CREATION", creation));
        const string expected = "file;scope;profile;key;changed;file|scope|profile|key|True";
        Assert.Equal(expected, await StatementOperationTestFixture.Run(document));
        var changed = await NamedArgumentTestFixture.Fix(document);
        Assert.Contains(creation + "(File: Next(\"file\"), Scope: Next(\"scope\"), Profile: Next(\"profile\"), Key: Next(\"key\"), Changed())",
            (await changed.GetTextAsync()).ToString());
        Assert.Equal(expected, await StatementOperationTestFixture.Run(await StatementOperationTestFixture.Reparse(changed)));
        Assert.Empty(await NamedArgumentTestFixture.Diagnostics(changed));
    }

    [Theory]
    [InlineData("new")]
    [InlineData("new SettingsEdit")]
    public async Task NamingDoesNotExtractTheComputedScope(string creation)
    {
        var source = """
            enum SettingsScope { User, Project }
            sealed record SettingsEdit(string File, string Scope, string? Profile, string Key, bool Changed);
            sealed class SettingsArguments { public string? Profile { get; set; } }
            static class C
            {
                static SettingsEdit Edit(string file, SettingsScope scope, SettingsArguments arguments, string key, bool changed)
                {
                    return CREATION(file, scope.ToString().ToLowerInvariant(), arguments.Profile, key, changed);
                }
            }
            """.Replace("CREATION", creation);
        var document = NamedArgumentTestFixture.Document(source);
        var changed = await NamedArgumentTestFixture.Fix(document);
        Assert.Contains("Scope: scope.ToString().ToLowerInvariant()", (await changed.GetTextAsync()).ToString());
        Assert.Empty(await NamedArgumentTestFixture.Diagnostics(changed));
        // These parameterless calls do not establish a CR03 producer. Naming
        // their constructor role is separate from extracting the scope value.
        Assert.Empty(await StatementOperationTestFixture.Diagnostics(document));
        Assert.Empty(await StatementOperationTestFixture.Diagnostics(changed));
    }

    private static string Read(string directory, string name) => File.ReadAllText(Path.Combine(AppContext.BaseDirectory, directory, name));

    private static async Task<string[]> ReturnBindings(Document document)
    {
        var root = await document.GetSyntaxRootAsync();
        var model = await document.GetSemanticModelAsync();
        return root!.DescendantNodes().OfType<ReturnStatementSyntax>()
            .Where(statement => statement.Expression is BaseObjectCreationExpressionSyntax
                && statement.Ancestors().OfType<MethodDeclarationSyntax>().First().Identifier.ValueText is "TargetTyped" or "Ordinary")
            .Select(statement => (IObjectCreationOperation)model!.GetOperation(statement.Expression!)!)
            .Select(operation => operation.Constructor!.ToDisplayString() + ":" + string.Join("|", operation.Arguments.Select(argument =>
                argument.Parameter!.Name + "=" + ((ArgumentSyntax)argument.Syntax).Expression.ToString())))
            .ToArray();
    }
}
