    [Fact]
    public async Task BundledRoslynatorConcatRuleDoesNotCoverA10Addition()
    {
        var document = StatementOperationTestFixture.Document("""
            using System.Globalization;
            class C
            {
                string Identifier(int index) => "desired-" + index.ToString(CultureInfo.InvariantCulture);
                string Lock(string file) => file + ".lock";
                string Alternative(string file) => string.Concat(file, ".lock");
            }
            """, "root = true\n[*.cs]\ndotnet_analyzer_diagnostic.severity = none\ndotnet_diagnostic.RCS1267.severity = warning\n");
        var candidates = typeof(Roslynator.CSharp.Analysis.UseBlockBodyOrExpressionBodyAnalyzer).Assembly.GetTypes()
            .Where(type => !type.IsAbstract && typeof(DiagnosticAnalyzer).IsAssignableFrom(type))
            .Select(type => (DiagnosticAnalyzer)Activator.CreateInstance(type)!)
            .Where(analyzer => analyzer.SupportedDiagnostics.Any(rule => rule.Id == "RCS1267")).ToImmutableArray();
        Assert.NotEmpty(candidates);
        var compilation = await document.Project.GetCompilationAsync();
        var diagnostics = await compilation!.WithAnalyzers(candidates, document.Project.AnalyzerOptions).GetAnalyzerDiagnosticsAsync();
        Assert.Equal("RCS1267", Assert.Single(diagnostics).Id);
    }

    [Fact]
    public async Task SharedA10FixturePreservesInvariantIdentifiersNullPathsAndBindings()
    {
        var document = StatementOperationTestFixture.Document(Read("StringConcatenation", "Consumer.cs"), Read("StringConcatenation", ".editorconfig"));
        var diagnostics = await Diagnostics(document);
        Assert.Equal(2, diagnostics.Length);
        Assert.All(diagnostics, diagnostic => Assert.Equal(DiagnosticSeverity.Warning, diagnostic.Severity));
        Assert.Contains("\"desired-\" + index.ToString(System.Globalization.CultureInfo.InvariantCulture)", diagnostics[0].Location.SourceTree!.GetText().ToString(diagnostics[0].Location.SourceSpan));
        Assert.Equal("file + \".lock\"", diagnostics[1].Location.SourceTree!.GetText().ToString(diagnostics[1].Location.SourceSpan));
        var bindings = await Bindings(document);
        const string expected = "desired--123|.lock|calendar.lock|~123";
        Assert.Equal(expected, await StatementOperationTestFixture.Run(document));
        document = await FixAll(document);
        Assert.Equal(Read("Expected", "StringConcatenation.Fixed.cs.txt"), (await document.GetTextAsync()).ToString());
        Assert.Equal(bindings, await Bindings(document));
        Assert.Equal(expected, await StatementOperationTestFixture.Run(document));
        Assert.Empty(await Diagnostics(document));
    }

