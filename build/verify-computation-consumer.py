#!/usr/bin/env python3
"""Verify ScheduleLib A6/A7/A8 computations against one stable candidate package."""

import argparse
from pathlib import Path
import re

from consumer_fixture import packaged_consumer
from manual_consumer import REPORT


DIAGNOSTICS = ["CR0300", "CR0301", "CR0302", "CR0203"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("package", type=Path, help="Existing nupkg or package directory (never repack here)")
    arguments = parser.parse_args()
    with packaged_consumer("Computations", arguments.package, parser) as (consumer, environment, run):
        config = consumer / ".editorconfig"

        def configure(severity):
            config.write_text("root = true\n\n[*.cs]\n"
                              "dotnet_analyzer_diagnostic.severity = none\n"
                              "dotnet_diagnostic.RCS0042.severity = none\n"
                              "dotnet_diagnostic.RCS1016.severity = none\n"
                              + "".join(f"dotnet_diagnostic.{rule}.severity = {severity}\n" for rule in DIAGNOSTICS))

        configure("warning")
        (consumer / "Generated.g.cs").write_text("""// <auto-generated/>
using System.Linq;
static class Generated {
    static int[] Path(bool flag, int[] parts) => flag
        ? new[] { 1 }.Concat(parts).ToArray() : new[] { 2 }.Concat(parts).ToArray();
    static bool Has(System.IServiceProvider provider, System.Type type) => provider.GetService(type) is null;
}
""")
        sources = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
        expected = set()
        for number, line in enumerate(sources["Findings.cs"].decode().splitlines(), start=1):
            if "// CR" not in line:
                continue
            code, markers = line.split("// ", 1)
            for rule, anchor in re.findall(r"(CR\d+): ([^|]+)", markers):
                expected.add(("Findings.cs", str(number), str(code.index(anchor.strip()) + 1), "warning", rule))
        assert len(expected) == 6, expected
        run(["dotnet", "restore", "Consumer.csproj"], consumer, environment)
        build = ["dotnet", "build", "Consumer.csproj", "--no-restore", "--no-incremental"]
        assert set(REPORT.findall(run(build, consumer, environment))) == expected
        behavior = run(["dotnet", "run", "--project", "Consumer.csproj", "--no-build"], consumer, environment)
        assert behavior.strip() == "True;6:1;paths;section;defaults/key:profiles/user/key;True:False", behavior
        errors = {(name, line, column, "error", rule) for name, line, column, _, rule in expected}
        assert set(REPORT.findall(run([*build, "-warnaserror"], consumer, environment, expected_returncode=1))) == errors
        configure("none")
        assert not REPORT.findall(run([*build, "-warnaserror"], consumer, environment))
        configure("error")
        assert set(REPORT.findall(run(build, consumer, environment, expected_returncode=1))) == errors
        configure("warning")
        # Diagnostic anchors are test metadata, not source comments that a fix
        # may move into another operation. Preserve ordinary comments; remove
        # only these anchors after checking their exact diagnostic locations.
        finding = consumer / "Findings.cs"
        finding.write_text(re.sub(r"[ \t]*// CR[0-9][^\r\n]*", "", finding.read_text()))
        command = ["dotnet", "format", "analyzers", "Consumer.csproj", "--no-restore", "--diagnostics", *DIAGNOSTICS]
        for attempt in range(8):
            previous = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
            run(command, consumer, environment)
            output = run(build, consumer, environment)
            if not REPORT.findall(output):
                break
            assert previous != {path.name: path.read_bytes() for path in consumer.glob("*.cs")}, output
        else:
            raise AssertionError("Computed-value fixes did not converge in eight passes")
        assert not REPORT.findall(run([*build, "-warnaserror"], consumer, environment))
        assert run(["dotnet", "run", "--project", "Consumer.csproj", "--no-build"], consumer, environment) == behavior
        fixed = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
        assert fixed["Accepted.cs"] == sources["Accepted.cs"]
        assert fixed["Generated.g.cs"] == sources["Generated.g.cs"]
        assert fixed["Findings.cs"] != sources["Findings.cs"]
        assert " = provider.GetService(" in fixed["Findings.cs"].decode()
        run(command, consumer, environment)
        assert {path.name: path.read_bytes() for path in consumer.glob("*.cs")} == fixed
        run([*command, "--verify-no-changes"], consumer, environment)
        print("PASS: six exact findings; accepted/generated cases; severity transport; computed-value "
              "and service-result fixes; unchanged runtime; saved-source stability; existing candidate package.")


if __name__ == "__main__":
    main()
