#!/usr/bin/env python3
"""Verify reviewed compound guards, filter fixes and accepted cases through the package."""

import argparse
from pathlib import Path
import re

from consumer_fixture import packaged_consumer
from manual_consumer import REPORT


DIAGNOSTICS = ["CR0200", "CR0201", "CR0202", "CR0203", "CR0204"]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("package", nargs="?", type=Path, help="Existing nupkg or package directory; otherwise pack")
    arguments = parser.parse_args()
    with packaged_consumer("ReviewedConditions", arguments.package, parser) as (consumer, environment, run):
        config = consumer / ".editorconfig"

        def configure(severity):
            config.write_text("root = true\n\n[*.cs]\n"
                              "dotnet_analyzer_diagnostic.severity = none\n"
                              "dotnet_diagnostic.RCS0042.severity = none\n"
                              "dotnet_diagnostic.RCS1016.severity = none\n"
                              + "".join(f"dotnet_diagnostic.{rule}.severity = {severity}\n" for rule in DIAGNOSTICS))

        configure("warning")
        (consumer / "Generated.g.cs").write_text("""// <auto-generated/>
class Generated {
    void Apply() {
        try { throw new GoogleApiException(400); }
        catch (GoogleApiException e) when ((int)e.HttpStatusCode is 400 or 403 or 404 or 409 or 412 or 422) { }
    }
}
""")
        sources = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
        expected = set()
        for number, line in enumerate(sources["Findings.cs"].decode().splitlines(), start=1):
            marker = re.search(r"// (CR\d+): (.+)$", line)
            if marker:
                anchor = line[:marker.start()].index(marker[2]) + 1
                expected.add(("Findings.cs", str(number), str(anchor), "warning", marker[1]))
        assert len(expected) == 6, expected
        run(["dotnet", "restore", "Consumer.csproj"], consumer, environment)
        build = ["dotnet", "build", "Consumer.csproj", "--no-restore", "--no-incremental"]
        output = run(build, consumer, environment)
        assert set(REPORT.findall(output)) == expected, output
        behavior = run(["dotnet", "run", "--project", "Consumer.csproj", "--no-build"], consumer, environment)
        caller_line = next(number for number, line in enumerate(sources["Accepted.cs"].decode().splitlines(), start=1)
                           if "return Line()" in line)
        assert behavior.splitlines()[-1] == f"{caller_line}ab", behavior
        assert behavior.count("rejected;") == 6, "The reviewed set must match exactly six statuses"
        errors = {(name, line, column, "error", rule) for name, line, column, _, rule in expected}
        output = run([*build, "-warnaserror"], consumer, environment, expected_returncode=1)
        assert set(REPORT.findall(output)) == errors, output
        configure("none")
        assert not REPORT.findall(run([*build, "-warnaserror"], consumer, environment))
        configure("error")
        assert set(REPORT.findall(run(build, consumer, environment, expected_returncode=1))) == errors
        configure("warning")
        command = ["dotnet", "format", "analyzers", "Consumer.csproj", "--no-restore", "--diagnostics", *DIAGNOSTICS]
        # The CLI selects one equivalence key per provider/pass. This family
        # deliberately has extraction-only filters and expansion-only out guards.
        # Bound the mixed-action workflow and require progress on every pass.
        remaining = len(expected)
        for attempt in range(3):
            run(command, consumer, environment)
            reports = set(REPORT.findall(run(build, consumer, environment)))
            assert len(reports) < remaining, ("No fixing progress", reports)
            if not reports:
                break
            remaining = len(reports)
        else:
            raise AssertionError("Reviewed fixes did not converge in three passes")
        output = run([*build, "-warnaserror"], consumer, environment)
        assert not REPORT.findall(output), output
        assert run(["dotnet", "run", "--project", "Consumer.csproj", "--no-build"], consumer, environment) == behavior
        fixed = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
        assert fixed["Accepted.cs"] == sources["Accepted.cs"]
        assert fixed["Generated.g.cs"] == sources["Generated.g.cs"]
        assert fixed["Findings.cs"] != sources["Findings.cs"]
        text = fixed["Findings.cs"].decode()
        assert "when (IsRejectedHttpStatusCode(e))" in text
        for member in ["BadRequest", "Forbidden", "NotFound", "Conflict", "PreconditionFailed", "UnprocessableEntity"]:
            assert "global::System.Net.HttpStatusCode." + member in text
        assert "out var key" in text and "out var operation" in text
        run(command, consumer, environment)
        assert {path.name: path.read_bytes() for path in consumer.glob("*.cs")} == fixed
        run([*command, "--verify-no-changes"], consumer, environment)
        print("PASS: six exact findings, accepted/generated cases, severity transport, packaged semantic fixes, "
              "all status matches and runtime trace, second-pass stability; isolated package.")


if __name__ == "__main__":
    main()
