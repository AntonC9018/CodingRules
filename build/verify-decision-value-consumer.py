#!/usr/bin/env python3
"""Verify saved CR0303 extraction, severity transport and source stability."""
import argparse
from pathlib import Path
from consumer_fixture import packaged_consumer
from manual_consumer import REPORT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('package', type=Path)
    args = parser.parse_args()
    with packaged_consumer('DecisionValues', args.package, parser) as (consumer, environment, run):
        config = consumer / '.editorconfig'
        def configure(severity):
            config.write_text('root=true\n[*.cs]\ndotnet_analyzer_diagnostic.severity=none\n'
                'dotnet_diagnostic.RCS0042.severity=none\ndotnet_diagnostic.RCS1016.severity=none\n'
                'dotnet_diagnostic.CR0303.severity=' + severity + '\n')
        configure('warning')
        (consumer / 'Generated.g.cs').write_text('''// <auto-generated/>
public static class Generated {
    public static bool M(bool flag) {
        bool result;
        if (flag) { result = true; } else { result = false; }
        return result;
    }
}
''')
        sources = {path.name: path.read_bytes() for path in consumer.glob('*.cs')}
        build = ['dotnet', 'build', 'Consumer.csproj', '--no-incremental']
        warnings = set(REPORT.findall(run(build, consumer, environment)))
        assert len(warnings) == 2 and all(item[4] == 'CR0303' for item in warnings), warnings
        configure('none')
        assert not REPORT.findall(run([*build, '-warnaserror'], consumer, environment))
        configure('error')
        errors = set(REPORT.findall(run(build, consumer, environment, expected_returncode=1)))
        assert errors == {(name, line, column, 'error', rule) for name, line, column, _, rule in warnings}, errors
        configure('warning')
        command = ['dotnet', 'format', 'analyzers', 'Consumer.csproj', '--no-restore', '--diagnostics', 'CR0303']
        run(command, consumer, environment)
        assert not REPORT.findall(run([*build, '-warnaserror'], consumer, environment))
        fixed = {path.name: path.read_bytes() for path in consumer.glob('*.cs')}
        assert fixed['Accepted.cs'] == sources['Accepted.cs']
        assert fixed['Generated.g.cs'] == sources['Generated.g.cs']
        assert b'bool CalculateValue()' in fixed['Findings.cs'] and b'return true;' in fixed['Findings.cs']
        run([*command, '--verify-no-changes'], consumer, environment)
        assert {path.name: path.read_bytes() for path in consumer.glob('*.cs')} == fixed
        print('PASS: two decision findings; severity; generated/accepted boundaries; saved extraction and stable second pass.')


if __name__ == '__main__':
    main()
