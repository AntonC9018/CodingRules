#!/usr/bin/env python3
"""Verify CR0403 against an explicit stable package, without repacking it."""

import argparse
from pathlib import Path

from consumer_fixture import packaged_consumer
from manual_consumer import REPORT


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("package", type=Path, help="Existing nupkg or package directory; never repack")
    arguments = parser.parse_args()
    with packaged_consumer("CompoundPredicates", arguments.package, parser) as (consumer, environment, run):
        config = consumer / ".editorconfig"

        def configure(severity):
            config.write_text("root = true\n\n[*.cs]\n"
                              "dotnet_analyzer_diagnostic.severity = none\n"
                              "dotnet_diagnostic.RCS0042.severity = none\n"
                              "dotnet_diagnostic.RCS1016.severity = none\n"
                              f"dotnet_diagnostic.CR0403.severity = {severity}\n")

        configure("warning")
        (consumer / "Generated.g.cs").write_text("""// <auto-generated/>
using System.Linq;
static class Generated {
    static bool Compound(int[] ids) => ids.Any(id => id > 0 && ids.Any(p => p == id));
    static bool Deep(int[] ids) => ids.Any(a => ids.Any(b => ids.Any(c => c == a)));
}
""")
        sources = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
        expected = set()
        for number, line in enumerate(sources["Findings.cs"].decode().splitlines(), start=1):
            if "// CR0403: " in line:
                code, anchor = line.split("// CR0403: ", 1)
                expected.add(("Findings.cs", str(number), str(code.index(anchor) + 1), "warning", "CR0403"))
        assert len(expected) == 2, expected
        run(["dotnet", "restore", "Consumer.csproj"], consumer, environment)
        build = ["dotnet", "build", "Consumer.csproj", "--no-restore", "--no-incremental"]
        output = run(build, consumer, environment)
        assert set(REPORT.findall(output)) == expected, output
        behavior = run(["dotnet", "run", "--project", "Consumer.csproj", "--no-build"], consumer, environment)
        assert behavior.strip() == "lab0|lab1|lab2|True|True|True|False|True|True|True|True", behavior

        errors = {(name, line, column, "error", rule) for name, line, column, _, rule in expected}
        output = run([*build, "-warnaserror"], consumer, environment, expected_returncode=1)
        assert set(REPORT.findall(output)) == errors, output
        configure("none")
        output = run([*build, "-warnaserror"], consumer, environment)
        assert not REPORT.findall(output), output
        configure("error")
        output = run(build, consumer, environment, expected_returncode=1)
        assert set(REPORT.findall(output)) == errors, output
        configure("warning")

        command = ["dotnet", "format", "analyzers", "Consumer.csproj", "--no-restore", "--diagnostics", "CR0403"]
        # The sequential Fix All validates final saved source after every edit.
        for attempt in range(3):
            previous = (consumer / "Findings.cs").read_bytes()
            run(command, consumer, environment)
            output = run(build, consumer, environment)
            if not REPORT.findall(output):
                break
            assert previous != (consumer / "Findings.cs").read_bytes(), output
        else:
            raise AssertionError("CR0403 fixes did not converge in three passes")

        output = run([*build, "-warnaserror"], consumer, environment)
        assert not REPORT.findall(output), output
        assert run(["dotnet", "run", "--project", "Consumer.csproj", "--no-build"], consumer, environment) == behavior
        fixed = {path.name: path.read_bytes() for path in consumer.glob("*.cs")}
        assert fixed["Accepted.cs"] == sources["Accepted.cs"]
        assert fixed["Generated.g.cs"] == sources["Generated.g.cs"]
        assert fixed["Findings.cs"] != sources["Findings.cs"]
        assert "return true;" in fixed["Findings.cs"].decode()
        assert "return false;" in fixed["Findings.cs"].decode()
        assert "CheckCondition" not in fixed["Findings.cs"].decode()
        run(command, consumer, environment)
        assert {path.name: path.read_bytes() for path in consumer.glob("*.cs")} == fixed
        run([*command, "--verify-no-changes"], consumer, environment)
        print("PASS: exact compound/depth findings; compact two-level and generated acceptance; "
              "severity transport; saved-source fixes; runtime and second-pass stability; explicit candidate.")


if __name__ == "__main__":
    main()
